<?php
/**
 * 한국어 전처리(형태소 분석기 없이 규칙 기반)
 *
 * 문장을 토큰으로 나눈 뒤, 한글 토큰 끝의 조사·어미를 떼어 "회의를/회의가/회의에서/회의는"이
 * 모두 "회의"가 되게 한다. 영어·숫자만으로 된 토큰은 건드리지 않는다.
 *
 * 이 결과는 TextRank 입력에만 쓰고, 저장·표시되는 요약 문장은 항상 원문 문장이다.
 */
final class KoreanPreprocessor
{
    /**
     * 떼어 낼 조사·어미. 긴 것부터 맞춰 본다(정렬은 코드에서 한다).
     * 값: 어간이 최소 몇 글자 남아야 떼는지.
     *  - 대부분 1(어간이 1글자 이상 남으면 뗌)
     *  - 명사 끝 글자와 자주 겹치는 한 글자 조사(이·가·도·만·의·나 등)는 2:
     *    "회의"(회+의), "아이"(아+이)처럼 원래 단어를 잘라 버리지 않도록 한다.
     */
    private const SUFFIXES = [
        // 조사(긴 것)
        '에서부터' => 1, '으로부터' => 1, '에게서는' => 1, '에서는' => 1, '에서도' => 1, '에서의' => 1, '으로는' => 1,
        '으로도' => 1, '으로서' => 1, '으로써' => 1, '에게서' => 1, '에게는' => 1, '에게도' => 1, '한테서' => 1,
        '한테는' => 1, '까지는' => 1, '까지도' => 1, '부터는' => 1, '부터도' => 1, '이라도' => 1, '이라는' => 1,
        '이라고' => 1, '이라면' => 1, '라고는' => 1, '처럼' => 1, '보다' => 1, '마저' => 1, '조차' => 1, '까지' => 1,
        '부터' => 1, '에서' => 1, '으로' => 1, '에게' => 1, '한테' => 1, '께서' => 1, '이나' => 1, '이랑' => 1,
        '와는' => 1, '과는' => 1, '이며' => 1, '이고' => 1, '라는' => 1, '라고' => 1, '로는' => 1, '로도' => 1,
        '로서' => 1, '로써' => 1, '에는' => 1, '에도' => 1, '에의' => 1, '만큼' => 1, '이란' => 1, '이요' => 1,
        // 어미(하다·되다·이다 계열 위주)
        '하였습니다' => 1, '했습니다' => 1, '되었습니다' => 1, '됐습니다' => 1, '하겠습니다' => 1, '합니다' => 1,
        '됩니다' => 1, '입니다' => 1, '하였다' => 1, '되었다' => 1, '이었다' => 1, '했다' => 1, '한다' => 1,
        '됐다' => 1, '된다' => 1, '였다' => 1, '이다' => 1, '하는' => 1, '하고' => 1, '하며' => 1, '해서' => 1,
        '했던' => 1, '했고' => 1, '하면' => 1, '하여' => 1, '되는' => 1, '되고' => 1, '되어' => 1, '됐고' => 1,
        '습니다' => 1, '었다' => 1, '았다' => 1, '겠다' => 1, '지만' => 1, '는데' => 1, '면서' => 1,
        // 조사(한 글자) — 명사 끝과 잘 겹치지 않는 것
        '을' => 1, '를' => 1, '은' => 1, '는' => 1, '에' => 1, '로' => 1, '와' => 1, '과' => 1,
        // 조사(한 글자) — 명사 끝과 자주 겹치는 것: 어간 2글자 이상일 때만
        '이' => 2, '가' => 2, '도' => 2, '만' => 2, '의' => 2, '나' => 2, '랑' => 2, '며' => 2,
    ];

    /** @var list<string>|null 긴 것부터 정렬한 접미사 목록 */
    private static ?array $ordered = null;

    /**
     * 문장 → 전처리된 토큰 목록(소문자, 조사·어미 제거)
     * @return list<string>
     */
    public static function tokens(string $sentence): array
    {
        // 글자·숫자가 아닌 것(문장부호, 공백, 기호, 이모지)은 모두 구분자로 본다
        $raw = preg_split('/[^\p{L}\p{N}]+/u', mb_strtolower($sentence), -1, PREG_SPLIT_NO_EMPTY) ?: [];
        return array_map([self::class, 'stem'], $raw);
    }

    /**
     * TextRank 입력용 한 줄: 토큰을 공백으로 이은 문자열.
     * 라이브러리의 문장 분리 규칙("\n", ". ", "? ", "! ")에 걸리지 않도록 문장부호가 없는 형태다.
     */
    public static function line(string $sentence): string
    {
        return implode(' ', self::tokens($sentence));
    }

    /** 토큰 하나의 끝에서 조사·어미 하나를 뗀다. 한글이 없는 토큰은 그대로 */
    public static function stem(string $token): string
    {
        if (!preg_match('/\p{Hangul}$/u', $token)) {
            return $token; // 영어·숫자 토큰, 또는 한글로 끝나지 않는 토큰
        }
        if (self::$ordered === null) {
            $keys = array_keys(self::SUFFIXES);
            usort($keys, static fn (string $a, string $b) => mb_strlen($b) <=> mb_strlen($a));
            self::$ordered = $keys;
        }
        $len = mb_strlen($token);
        foreach (self::$ordered as $suffix) {
            $sLen = mb_strlen($suffix);
            if ($sLen >= $len || mb_substr($token, -$sLen) !== $suffix) {
                continue;
            }
            $stem = mb_substr($token, 0, $len - $sLen);
            if (mb_strlen($stem) >= self::SUFFIXES[$suffix]) {
                return $stem;
            }
        }
        return $token;
    }
}
